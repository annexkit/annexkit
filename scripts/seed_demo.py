"""Seed a demo tenant + 3 AI systems for the public trust page.

Production-safe — bypasses the dev-only guard in seed_tenant.py because
this script never prints sensitive data unless explicitly asked. The
tenant is named "Acme SaaS" with slug "acme-saas" so the resulting
trust page lives at https://annexkit.dev/trust/acme-saas.

What it creates
---------------

  * One tenant ("Acme SaaS S.r.l.", slug "acme-saas").
  * One API key for that tenant — printed once on success.
  * Three AI system declarations covering the three risk-tier badges
    a homepage visitor should see:
      - customer-support-bot  — LIMITED (Article 50 transparency)
      - cv-screener           — HIGH    (Annex III §4 employment)
      - loan-prescreen        — HIGH    (Annex III §5 essential services)

The demo systems use sanitised provider info pointing at AnnexKit
itself as the "provider" — clearly a demo, not a real third party.

Usage
-----

  # Inside the running backend container:
  docker compose cp scripts/seed_demo.py backend:/tmp/seed_demo.py
  docker compose exec backend uv run python /tmp/seed_demo.py

To use a different slug:

  docker compose exec backend uv run python /tmp/seed_demo.py my-slug

To re-run idempotently (the tenant already exists):

  docker compose exec backend uv run python /tmp/seed_demo.py acme-saas

  → prints "tenant exists, api_key=…" if a key already exists, or mints
    a new one if not.

Idempotence notes
-----------------

  * Tenants are looked up by slug; rerunning with the same slug reuses
    the existing tenant.
  * AI systems are upserted via the same service the API uses
    (`ai_system_service.upsert`), so the deterministic risk classifier
    runs and the audit log records create-or-update events.
  * API keys are NOT regenerated if one already exists — a fresh key is
    only minted the first run, and the printout warns when reusing.
"""

