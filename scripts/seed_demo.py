async def main() -> int:
    slug = sys.argv[1] if len(sys.argv) > 1 else "acme-saas"
    name = "Acme SaaS S.r.l. (demo)"

    async with AsyncSessionLocal() as session:
        # 1. tenant — create if missing, reuse if present.
        existing = await session.scalar(
            select(Tenant).where(Tenant.slug == slug)
        )
        if existing is None:
            tenant = Tenant(name=name, slug=slug)
            session.add(tenant)
            await session.flush()
            new_tenant = True
        else:
            tenant = existing
            new_tenant = False

        # 2. API key — only mint a fresh one if there is none yet.
        existing_key = await session.scalar(
            select(ApiKey).where(ApiKey.tenant_id == tenant.id)
        )
        if existing_key is None:
            generated = api_key_service.generate()
            session.add(
                ApiKey(
                    tenant_id=tenant.id,
                    name="seed-demo",
                    key_prefix=generated.prefix,
                    key_hash=generated.key_hash,
                )
            )
            api_key_plaintext = generated.plaintext
        else:
            api_key_plaintext = None  # cannot recover — was hashed.

        # 3. AI systems — upsert via the service so the deterministic
        #    classifier runs and the audit log records the event.
        for declaration in DEMO_SYSTEMS:
            await ai_system_service.upsert(
                session,
                tenant_id=tenant.id,
                payload=declaration,
            )

        await session.commit()

    # ---- Output -----------------------------------------------------
    print()
    print(f"slug={slug}")
    print(f"tenant_id={tenant.id}")
    print(f"tenant_status={'created' if new_tenant else 'reused'}")
    if api_key_plaintext:
        print(f"api_key={api_key_plaintext}")
        print()
        print("Copy api_key now — it is hashed in the DB and unrecoverable.")
    else:
        print("api_key=<existing — not shown; mint a new one via the API>")
    print()
    print("Demo trust page is now live:")
    print(f"  https://annexkit.dev/trust/{slug}")
    print(f"  https://annexkit.dev/trust/{slug}/systems/customer-support-bot")
    print(f"  https://annexkit.dev/trust/{slug}/systems/cv-screener")
    print(f"  https://annexkit.dev/trust/{slug}/systems/loan-prescreen")
    print()
    print(f"Seeded at {datetime.now(UTC).isoformat()}.")
    return 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
